export function getCodex(typeId: string): CodexEntry | undefined {
  return CODEX.find((c) => c.typeId === typeId);
}

/** 按课程分级筛选图鉴 */
export function codexByLevel(level: CodexEntry["courseLevel"]): CodexEntry[] {
  return CODEX.filter((c) => c.courseLevel === level);
}

/** 已解锁图鉴数 / 总数（用于学习进度计算） */
export function codexProgress(unlockedTypeIds: string[]): {
  unlocked: number;
  total: number;
  byLevel: { level: CodexEntry["courseLevel"]; unlocked: number; total: number }[];
} {
  const set = new Set(unlockedTypeIds);
  const levels: CodexEntry["courseLevel"][] = ["basic", "intermediate", "advanced"];
  const byLevel = levels.map((level) => {
    const list = CODEX.filter((c) => c.courseLevel === level);
    return {
      level,
      unlocked: list.filter((c) => set.has(c.typeId)).length,
      total: list.length,
    };
  });
  return {
    unlocked: CODEX.filter((c) => set.has(c.typeId)).length,
    total: CODEX.length,
    byLevel,
  };
}
