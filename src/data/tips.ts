export function randomTip(seed?: number): AntiFraudTip {
  if (seed === undefined) return TIPS[Math.floor(Math.random() * TIPS.length)];
  return TIPS[seed % TIPS.length];
}

/** 按反诈类型 ID 筛选相关锦囊（用于学习卡片） */
export function tipsByType(typeId: FraudTypeId): AntiFraudTip[] {
  return TIPS.filter((t) => t.typeId === typeId);
}
